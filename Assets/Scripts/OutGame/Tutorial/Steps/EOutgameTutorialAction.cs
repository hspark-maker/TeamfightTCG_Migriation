// 스텝 한 행이 "무엇을 하는가". 스텝 SO 클래스 10종을 대신하는 저작 축이다 —
// 완료 조건·씬 이탈 여부·인스펙터에 뜨는 필드가 전부 이 값 하나에서 파생된다(TutorialStepDef).
// 시퀀스에 int로 직렬화 → 새 값은 반드시 끝에만 추가. 기존 값 재배치·삭제 금지(저작된 행이 엉뚱한 액션이 된다).
public enum EOutgameTutorialAction
{
    WaitClick     = 0,    // 앵커 클릭 대기. 클릭이 곧 완료다(눌러서 실패할 여지가 없는 이동·획득 버튼용)
    Message       = 1,    // 화면 탭으로 넘기는 설명. 앵커는 "강조할 영역"이라 옵션이고 Button도 필요 없다
    WaitPurchase  = 2,    // 상점 구매 대기. 클릭이 아니라 구매 "성공"이 완료다(골드 부족 시 실패)
    WaitPackOpen  = 3,    // 팩 개봉 대기. 걸 앵커가 없어(개봉 팩은 딤을 못 뚫는다) 배너만 띄운다
    DeckAutoEquip = 4,    // 덱 자동 편성 버튼 클릭 대기. 편성 결과를 지정 팩으로 덮어쓴다
    BattleEntry   = 5,    // 앵커 클릭으로 전투 진입. showDeckGate를 켜면 덱 화면을 거친다
    BattleStart   = 6,    // 덱 확인 화면의 전투 시작 버튼 클릭 대기. 클릭이 곧 전투 개시다
    AutoBattle    = 7,    // 입력 없이 곧장 전투로. 로비를 거치지 않는 첫 전투용
    AutoPurchase  = 8,    // 입력 없이 팩을 구매해 개봉 오버레이를 연다. 씬은 그대로다
    DeckGrant     = 9,    // 완성된 덱을 유저 세이브에 미리 지급한다. 입력 없음
}
