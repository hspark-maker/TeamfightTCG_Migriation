using System;

// 랭크(표시용 티어 진행도)의 세이브 값 객체.
// 필드는 추가만(하위호환) — 의미 변경·삭제·리네임 금지. 구 세이브엔 노드가 없어 기본값(0)으로 읽힌다.
[Serializable]
public class RankSaveData
{
    // 티어는 이 값의 순수 파생이다 — 도달 티어를 따로 저장하면 둘이 어긋날 때 어느 쪽이 진실인지 알 수 없다.
    public long points;

    // 수령 완료한 티어 개수(단조 증가 커서). 티어는 강등이 없고 순차 수령이라 값 하나로 20행 상태가 파생된다(i < claimedCount = 수령 완료).
    // 센티널(-1)이 아니라 개수인 이유: 기본값 0이 곧 미수령이라 구 세이브·노드 재작성 경로에서도 "이미 받음"으로 오판할 수 없다.
    public int claimedCount;
}
